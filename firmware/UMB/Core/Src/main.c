// Selects the hardware Mux channel (0-7)
void Set_Mux_Channel(uint8_t channel) {
    HAL_GPIO_WritePin(MUX_PORT, MUX_EN, GPIO_PIN_SET); // Enable Mux
    HAL_GPIO_WritePin(MUX_PORT, MUX_A0, (channel & 0x01) ? GPIO_PIN_SET : GPIO_PIN_RESET);
    HAL_GPIO_WritePin(MUX_PORT, MUX_A1, (channel & 0x02) ? GPIO_PIN_SET : GPIO_PIN_RESET);
    HAL_GPIO_WritePin(MUX_PORT, MUX_A2, (channel & 0x04) ? GPIO_PIN_SET : GPIO_PIN_RESET);
}

// Simple Write for PGA280 (Standard 3-byte SPI frame: Addr, Data, Checksum/Zero)
void PGA280_Write(uint8_t reg, uint8_t value) {
    uint8_t data[3] = { reg, value, 0x00 };
    HAL_GPIO_WritePin(PGA_CS_PORT, PGA_CS_PIN, GPIO_PIN_RESET);
    HAL_SPI_Transmit(&hspi1, data, 3, 10);
    HAL_GPIO_WritePin(PGA_CS_PORT, PGA_CS_PIN, GPIO_PIN_SET);
}

// Reads 16-bit value from ADS8863
uint16_t ADC_Read(void) {
    uint8_t raw[2] = {0};
    HAL_GPIO_WritePin(ADC_CS_PORT, ADC_CS_PIN, GPIO_PIN_RESET);
    // ADS8863 requires clocking out 16 bits to get conversion data
    HAL_SPI_Receive(&hspi1, raw, 2, 10);
    HAL_GPIO_WritePin(ADC_CS_PORT, ADC_CS_PIN, GPIO_PIN_SET);
    return (uint16_t)((raw[0] << 8) | raw[1]);
}
